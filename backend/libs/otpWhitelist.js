export const isWhitelisted = (phoneNumber) => {
    if (!phoneNumber) return false;
    // Remove any non-digit characters for robust matching
    const cleanNumber = phoneNumber.toString().replace(/\D/g, '');

    return whitelistedNumbers.some(wn => {
        const cleanWhitelisted = wn.toString().replace(/\D/g, '');
        // Match if one ends with another (handles +91 vs local number)
        return cleanNumber.endsWith(cleanWhitelisted) || cleanWhitelisted.endsWith(cleanNumber);
    });
};
